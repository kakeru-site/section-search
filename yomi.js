const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const RE = new RegExp(
  Object.keys(D)
    .sort((a, b) => b.length - a.length)
    .map(esc)
    .join("|"),
  "g",
);
// 漢字をひらがなの読みに置き換える（alt=1 で、2通りある言葉の2番目の読み）
export function yomiText(s, alt = 0) {
  return String(s ?? "")
    .normalize("NFKC")
    .replace(RE, (m) => {
      const v = D[m].split("|");
      return v[alt] ?? v[0];
    });
}
